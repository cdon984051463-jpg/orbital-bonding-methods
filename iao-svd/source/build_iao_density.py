"""Build a transferable IAO density matrix directly from a VASP PAW calculation.

This replaces steps 01 (regional Schmidt eigensolve) and 03 (region-set Lowdin
coverage) of the q214 reference chain for the specific purpose of comparing the
SAME bond across several structures.

Why not reuse 01+03
-------------------
In the q214 chain the atom-side subspace X_A is a column slice of the symmetric
Lowdin factor of the 22 IAO columns belonging to ONE region
{Ru1,O73,O91,O93,O110,O113,H115}. Symmetric orthogonalisation mixes all 22
columns, so X_Ru depends on which atoms are in the region. Removing the OH
hydrogen, or moving to a structure with a different adsorbate, redefines X_Ru
and X_O even at frozen geometry, and the singular values then differ for
reasons that have nothing to do with the bond. On top of that the retained
active dimension is chosen by a positive-mass target and varies per structure.

Here the density is expressed in the FULL-CELL Lowdin IAO basis instead. Those
columns are generated by fixed free-atom templates and a fixed POTCAR, they
cover every atom in the cell, and no active-space truncation is applied: the
whole occupied window is kept and the basis closes exactly. Atom A's subspace
is then simply "the columns labelled A", defined identically in every
structure.

Definition
----------
For occupied Bloch states psi_nk with k weights w_k and occupations f_nk,

    D_(mu,nu) = sum_nk  w_k f_nk  <IAO_mu|psi_nk> <psi_nk|IAO_nu>

which is Hermitian and positive semi-definite. With complete time-reversal
k pairing the imaginary part cancels; that cancellation is checked, not assumed.
D is then diagonalised, D = W L W^T, and written in the form the PDC core
expects: eigenvalues L, and basis X = W^T whose column mu holds the coordinates
of IAO_mu. This is an exact rewriting, not a truncation, so

    X_A^T diag(L) X_B  ==  D[A, B]

with X orthonormal and complete.

The default ``o2s`` basis includes O 2s+2p and the complete occupied band window.
The explicit legacy ``valence`` basis excludes the O 2s manifold (the lowest
n_O bands, separated here by ~10 eV) from both the window and the template.
"""


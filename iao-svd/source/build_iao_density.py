def potcar_records(path: Path) -> list[dict]:
    records = []
    for block in path.read_text(errors="replace").split("End of Dataset")[:-1]:
        def field(pattern: str) -> str:
            match = re.search(pattern, block, re.MULTILINE)
            if not match:
                raise ValueError(f"cannot parse POTCAR metadata in {path.name}")
            return match.group(1).strip()

        vrhfin = field(r"^\s*VRHFIN\s*=\s*(.*?)\s*$")
        records.append(
            {
                "element": vrhfin.split(":", 1)[0].strip(),
                "titel": field(r"^\s*TITEL\s*=\s*(.*?)\s*$"),
                "zval": float(field(r"ZVAL\s*=\s*([-+0-9.Ee]+)")),
                "valence_configuration": vrhfin.split(":", 1)[1].strip(),
                "_normalized_dataset": re.sub(r"\s+", " ", block).strip(),
            }
        )
    if not records:
        raise ValueError(f"no POTCAR datasets found in {path}")
    return records


def validate_potcar_templates(calc: Path, element_order: list[str], shells: dict) -> dict:
    """Compare the calculation POTCAR against the fixed IAO templates.

    Structural problems (order mismatch, missing template, unparseable dataset)
    raise immediately because nothing downstream could run. The dataset-identity
    and standard-Ru conditions are instead returned as recorded booleans and are
    evaluated by the pass gate, so that gate entry is load-bearing rather than a
    literal True that can never fail.
    """
    main = potcar_records(calc / "POTCAR")
    if [record["element"] for record in main] != element_order:
        raise RuntimeError(
            f"POTCAR order {[record['element'] for record in main]} does not match "
            f"CONTCAR order {element_order}"
        )
    templates, identity = {}, {}
    for record in main:
        element = record["element"]
        if element not in TEMPLATE_DIRS or element not in shells:
            raise RuntimeError(f"no fixed IAO template/shell definition for element {element}")
        template = potcar_records(TEMPLATE_DIRS[element] / "POTCAR")
        if len(template) != 1 or template[0]["element"] != element:
            raise RuntimeError(f"template POTCAR for {element} must contain exactly that dataset")
        template = template[0]
        same_dataset = record.pop("_normalized_dataset") == template.pop("_normalized_dataset")
        templates[element] = template
        identity[element] = {
            "dataset_match": same_dataset,
            "main_titel": record["titel"],
            "template_titel": template["titel"],
        }

    ru = next((record for record in main if record["element"] == "Ru"), None)
    if ru is None:
        ru_evidence = {"present": False, "standard_ru_ok": True}
    else:
        configuration = re.sub(r"\s+", "", ru["valence_configuration"]).lower()
        not_semicore = not re.search(r"\bRu_(?:pv|sv)\b", ru["titel"], re.IGNORECASE)
        zval_ok = bool(np.isclose(ru["zval"], 8.0))
        configuration_ok = configuration == "s1d7"
        ru_evidence = {
            "present": True,
            "titel": ru["titel"],
            "zval": ru["zval"],
            "valence_configuration": ru["valence_configuration"],
            "titel_not_pv_or_sv": not_semicore,
            "zval_is_8": zval_ok,
            "configuration_is_s1d7": configuration_ok,
            "standard_ru_ok": bool(not_semicore and zval_ok and configuration_ok),
            "requirement": (
                "this 5s+4d template with an O-2s band window requires standard Ru "
                "(ZVAL=8, VRHFIN s1 d7); Ru_pv/Ru_sv carry 4p valence bands and need a "
                "different template and band window"
            ),
        }
    return {
        "main": main,
        "templates": templates,
        "dataset_identity": identity,
        "ru": ru_evidence,
        "all_datasets_match": all(item["dataset_match"] for item in identity.values()),
        "standard_ru_ok": ru_evidence["standard_ru_ok"],
    }


def incar_value(text: str, name: str) -> str | None:
    clean = "\n".join(line.split("!", 1)[0].split("#", 1)[0] for line in text.splitlines())
    matches = re.findall(rf"(?im)(?:^|;)\s*{re.escape(name)}\s*=\s*([^;\s]+)", clean)
    return matches[-1] if matches else None


def realify(matrix: np.ndarray) -> np.ndarray:
    result = np.empty((2 * len(matrix), matrix.shape[1]), dtype=np.float64)
    result[0::2], result[1::2] = matrix.real, matrix.imag
    return result


def real_space_gauge(grid: np.ndarray) -> tuple[np.ndarray, dict]:
    """Restore the time-reversal gauge of real isolated-atom orbitals."""
    corrected = grid.copy()
    errors = []
    for index, reciprocal in enumerate(corrected):
        field = np.fft.ifftn(reciprocal)
        phase = np.exp(-0.5j * np.angle(np.sum(field * field)))
        gauged = phase * field
        if np.linalg.norm(gauged.imag) > np.linalg.norm(gauged.real):
            phase *= 1j
            gauged *= 1j
        corrected[index] *= phase
        errors.append(float(np.linalg.norm(gauged.imag) / np.linalg.norm(gauged.real)))
    return corrected, {"maximum_imaginary_to_real_norm_ratio": max(errors)}


def verify_time_reversal(calc: Path, kvectors: np.ndarray, multiplicities: np.ndarray) -> dict:
    """Validate the nonmagnetic folding mode used by an ISYM=0/1 calculation.

    The accumulated D is Hermitian, so its imaginary part is antisymmetric. For a
    non-magnetic calculation without spin-orbit coupling, psi_{n,-k} = psi*_{n,k}
    and the IAO templates are real, so the -k contribution to D is the complex
    conjugate of the +k contribution. When -k is folded onto k inside the same
    IBZ weight, the antisymmetric imaginary part therefore cancels exactly and
    Re[D] is the physical density -- an identity, not a truncation.

    For ISYM=0 this only holds if every non-TRIM multiplicity is even, so that is
    checked rather than assumed.  For ISYM=1 the multiplicity also contains
    spatial images; those are expanded explicitly later by
    ``space_group_expansion`` and checked against the automatic full k mesh.
    """
    incar = (calc / "INCAR").read_text(errors="replace")

    def flag(name: str) -> bool:
        value = incar_value(incar, name)
        return value is not None and value.strip().upper().startswith((".T", "T", "1"))

    spin_value = incar_value(incar, "ISPIN")
    spin = int(spin_value) if spin_value is not None else 1
    isym_value = incar_value(incar, "ISYM")
    problems = []
    try:
        isym = int(isym_value) if isym_value is not None else None
    except ValueError:
        isym = None
    if isym not in (0, 1):
        problems.append(
            f"ISYM={isym_value or 'default'}; validated modes are ISYM=0 and ISYM=1"
        )
    if spin != 1:
        problems.append(f"ISPIN={spin} (collinear spin polarisation)")
    if flag("LSORBIT"):
        problems.append("LSORBIT is on (spin-orbit coupling)")
    if flag("LNONCOLLINEAR"):
        problems.append("LNONCOLLINEAR is on")

    folded = np.asarray(kvectors) * 2.0
    is_trim = np.all(np.abs(folded - np.round(folded)) < 1.0e-8, axis=1)
    if isym == 0:
        for index, (multiplicity, trim) in enumerate(zip(multiplicities, is_trim)):
            if multiplicity % 2 and not trim:
                problems.append(
                    f"k point {index + 1} has odd multiplicity {multiplicity} and is not a TRIM point"
                )
    if problems:
        raise RuntimeError(
            "The nonmagnetic ISYM=0/1 folding contract cannot be established: "
            + "; ".join(problems)
        )
    return {
        "argument": "psi(-k) = conj(psi(k)) with real IAO templates, so the -k term is the "
                    "conjugate of the +k term and the antisymmetric imaginary part cancels",
        "ISYM": isym,
        "folding_mode": (
            "time reversal only; stored IBZ blocks retained"
            if isym == 0 else
            "space group plus time reversal; explicit full-k expansion required"
        ),
        "ISPIN": spin,
        "LSORBIT": flag("LSORBIT"),
        "LNONCOLLINEAR": flag("LNONCOLLINEAR"),
        "multiplicities": multiplicities.tolist(),
        "trim_points_1based": (np.flatnonzero(is_trim) + 1).tolist(),
    }


def reference_layout(structure, shells: dict) -> tuple[list[dict], list[list[int]]]:
    rows, atom_columns, cursor = [], [], 0
    for atom_index, site in enumerate(structure.sites, start=1):
        bands, shell, _ = shells[site.element]
        columns = list(range(cursor, cursor + len(bands)))
        atom_columns.append(columns)
        for column, band in zip(columns, bands):
            rows.append(
                {
                    "reference_column": column,
                    "atom_index_1based": atom_index,
                    "element": site.element,
                    "atomic_band_index_1based": band,
                    "active_shell": shell,
                }
            )
        cursor += len(columns)
    return rows, atom_columns


def build_reference(structure, g_plus_k, reciprocal, main_volume, grids, diagnostics, width):
    bases = {}
    for element in grids:
        block, _ = interpolate_template_to_main_g(
            grids[element],
            np.asarray(diagnostics[element]["lattice_A"], dtype=np.float64),
            g_plus_k,
            reciprocal,
        )
        block *= np.sqrt(float(diagnostics[element]["volume_A3"]) / main_volume)
        bases[element] = block
    reference = np.empty((width, len(g_plus_k)), dtype=np.complex128)
    cursor = 0
    for site in structure.sites:
        block = bases[site.element]
        stop = cursor + len(block)
        phase = np.exp(-2j * np.pi * (g_plus_k @ np.asarray(site.fractional, dtype=np.float64)))
        reference[cursor:stop] = block * phase[None, :]
        cursor = stop
    if cursor != width:
        raise RuntimeError(f"expected {width} reference columns, built {cursor}")
    return reference


def empty_band_reference_overlap(wav, k_index, band_indices, reference, atoms, datasets):
    """PAW cross overlap <psi_empty|reference> for bands outside the window.

    Only the reference block is needed: an empty band is PAW-orthogonal to every
    occupied band, so inside the joint (occupied + reference) Gram its coordinates
    come entirely through its overlap with the atomic templates.
    """
    empty = np.stack(
        [np.asarray(wav.coeffs(k_index, band), dtype=np.complex128) for band in band_indices]
    )
    cross = empty.conj() @ reference.T
    qengine = nonlq(atoms, wav.encut, datasets,
                    k=np.asarray(wav.kinfo[k_index][1], dtype=np.float64))
    for start in range(0, len(atoms), 16):
        stop = min(start + 16, len(atoms))
        projectors = [paw_core.atom_projector_matrix(qengine, atom) for atom in range(start, stop)]
        widths = [len(projector) for projector in projectors]
        stacked = np.concatenate(projectors, axis=0)
        empty_beta_all = empty @ stacked.T
        reference_beta_all = reference @ stacked.T
        offset = 0
        for local, atom_index in enumerate(range(start, stop)):
            width = widths[local]
            correction = np.asarray(
                datasets[qengine.element_idx[atom_index]].get_Qij(), dtype=np.complex128
            )
            cross += (
                empty_beta_all[:, offset : offset + width].conj()
                @ correction
                @ reference_beta_all[:, offset : offset + width].T
            )
            offset += width
    del empty, qengine
    return cross


def project_onto_iao(joint_overlap_rows, joint_coordinates, coordinates_gram, iaos):
    """<psi|IAO> from a state's overlap row against the joint (occupied+reference) basis.

    With coordinates = sqrt(L) V^dagger, coordinates coordinates^dagger = L is
    diagonal, so the abstract coordinate vector of a state whose overlap row is t
    is x^dagger = t coordinates^dagger L^-1 -- a diagonal solve, no pseudoinverse.
    The identity is exact for any state inside the joint span, which is why
    feeding it the occupied rows must return the independently built factors.
    """
    return (
        joint_overlap_rows
        @ joint_coordinates.conj().T
        @ np.diag(1.0 / coordinates_gram)
        @ iaos
    )


def build_paw_grams(wav, k_index, band_indices, reference, atoms, datasets, augment=True):
    occupied = np.stack(
        [np.asarray(wav.coeffs(k_index, band), dtype=np.complex128) for band in band_indices]
    )
    occupied_overlap = occupied.conj() @ occupied.T
    cross_overlap = occupied.conj() @ reference.T
    reference_overlap = reference.conj() @ reference.T

    kvector = np.asarray(wav.kinfo[k_index][1], dtype=np.float64)
    gvec = wav.gvecs(k_index)
    if not augment:
        # DIAGNOSTIC ONLY: pseudo-wavefunction overlaps with no Q_ij augmentation.
        # This is not a valid physical metric; it exists to quantify what the PAW
        # augmentation actually contributes for Ru 4d.
        occupied_overlap = 0.5 * (occupied_overlap + occupied_overlap.conj().T)
        reference_overlap = 0.5 * (reference_overlap + reference_overlap.conj().T)
        return (
            {"occupied_overlap": occupied_overlap, "cross_overlap": cross_overlap,
             "reference_overlap": reference_overlap},
            {"occupied_PAW_orthonormality_max_abs_error": float(
                np.max(np.abs(occupied_overlap - np.eye(len(occupied_overlap))))),
             "finite": True, "augmented": False},
        )
    qengine = nonlq(atoms, wav.encut, datasets, k=kvector)
    if not np.array_equal(gvec, qengine.Gvec):
        raise RuntimeError(f"WAVECAR/PAW reciprocal-vector order mismatch at k={k_index + 1}")

    for start in range(0, len(atoms), 16):
        stop = min(start + 16, len(atoms))
        projectors = [paw_core.atom_projector_matrix(qengine, atom) for atom in range(start, stop)]
        widths = [len(projector) for projector in projectors]
        stacked = np.concatenate(projectors, axis=0)
        occupied_beta_all = occupied @ stacked.T
        reference_beta_all = reference @ stacked.T
        offset = 0
        for local, atom_index in enumerate(range(start, stop)):
            width = widths[local]
            occupied_beta = occupied_beta_all[:, offset : offset + width]
            reference_beta = reference_beta_all[:, offset : offset + width]
            correction = np.asarray(
                datasets[qengine.element_idx[atom_index]].get_Qij(), dtype=np.complex128
            )
            occupied_overlap += occupied_beta.conj() @ correction @ occupied_beta.T
            cross_overlap += occupied_beta.conj() @ correction @ reference_beta.T
            reference_overlap += reference_beta.conj() @ correction @ reference_beta.T
            offset += width

    occupied_overlap = 0.5 * (occupied_overlap + occupied_overlap.conj().T)
    reference_overlap = 0.5 * (reference_overlap + reference_overlap.conj().T)
    diagnostics = {
        "occupied_PAW_orthonormality_max_abs_error": float(
            np.max(np.abs(occupied_overlap - np.eye(len(occupied_overlap))))
        ),
        "finite": bool(
            np.isfinite(occupied_overlap).all()
            and np.isfinite(cross_overlap).all()
            and np.isfinite(reference_overlap).all()
        ),
    }
    del occupied, reference
    return (
        {
            "occupied_overlap": occupied_overlap,
            "cross_overlap": cross_overlap,
            "reference_overlap": reference_overlap,
        },
        diagnostics,
    )


def build_k_context(calc: Path, basis_variant: str, occupation_floor: float,
                    skip_augmentation: bool, spectral_empty_bands: int,
                    with_template_tests: bool = True,
                    with_space_group_plan: bool = True) -> dict:
    """Everything that does not depend on k, plus an open WAVECAR handle.

    Built once in the parent for a serial run, and once per process for a
    parallel one, so both paths feed exactly the same objects to _process_k.
    The caller must close ``context["wav"]``.
    """
    shells = shell_table(basis_variant)
    structure = parse_poscar(calc / "CONTCAR")
    atoms = ase_read(calc / "CONTCAR")
    element_order = list(dict.fromkeys(site.element for site in structure.sites))
    potcar_validation = validate_potcar_templates(calc, element_order, shells)
    datasets = parse_paw_datasets(calc / "POTCAR")
    elements = sorted({site.element for site in structure.sites})
    counts = {element: sum(1 for s in structure.sites if s.element == element) for element in elements}
    n_oxygen = counts.get("O", 0)

    # Window rule, coupled to the template so the two can never disagree: the
    # deep O 2s manifold (exactly the lowest n_O bands) is excluded from the
    # window if and only if the O template does not carry a 2s function.
    oxygen_2s_in_template = "O" in shells and shells["O"][0][0] == 1
    n_excluded = 0 if oxygen_2s_in_template else n_oxygen

    outcar_text = (calc / "OUTCAR").read_text(errors="replace")
    fermi = float(re.findall(r"E-fermi\s*:\s*([-+0-9.Ee]+)", outcar_text)[-1])
    nelect = float(re.findall(r"NELECT\s*=\s*([-+0-9.Ee]+)", outcar_text)[-1])
    kvectors, multiplicities, k_weights = base.read_ibzkpt(calc / "IBZKPT")
    k_weights = np.asarray(k_weights, dtype=np.float64)
    kvectors = np.asarray(kvectors, dtype=np.float64)
    multiplicities = np.asarray(multiplicities, dtype=int)
    time_reversal = verify_time_reversal(calc, kvectors, multiplicities)
    if time_reversal["ISYM"] == 1 and basis_variant not in ("valence", "o2s"):
        raise RuntimeError(
            "ISYM=1 supports the valence and o2s bases; "
            f"basis_variant={basis_variant!r} is a convergence variant"
        )

    labels, atom_columns = reference_layout(structure, shells)
    width = len(labels)

    grids, template_diag, template_tests = {}, {}, {}
    virtual_template_orbitals = {}
    for element in elements:
        bands, shell_name, load_count = shells[element]
        # The loader normally insists every loaded majority orbital is occupied.
        # A variant that includes an empty atomic shell has to switch that guard
        # off, so the occupied part of the guard is re-applied here explicitly
        # and the empty orbitals are reported as evidence rather than hidden.
        occupied_in_free_atom = FREE_ATOM_OCCUPIED[element]
        strict = load_count <= occupied_in_free_atom
        raw, diag = load_centered_atomic_template(
            TEMPLATE_DIRS[element], load_count, OCCUPIED_ONLY if strict else ALLOW_VIRTUAL
        )
        template_occupations = np.asarray(diag["majority_spin_occupations"], dtype=float)
        if not strict:
            filled = template_occupations[:occupied_in_free_atom]
            if np.max(np.abs(filled - 1.0)) > OCCUPIED_ONLY:
                raise RuntimeError(
                    f"{element} template: the first {occupied_in_free_atom} majority orbitals "
                    f"are not the occupied shell (max |f - 1| = {np.max(np.abs(filled - 1.0)):.3e})"
                )
            if np.max(template_occupations[occupied_in_free_atom:load_count]) > 1.0e-8:
                raise RuntimeError(
                    f"{element} template: orbitals beyond {occupied_in_free_atom} are not empty, "
                    "so the free-atom shell assignment of this variant is wrong"
                )
        raw, gauge = real_space_gauge(raw)
        grids[element] = raw[bands[0] - 1 : bands[-1]]
        kept_occupations = template_occupations[bands[0] - 1 : bands[-1]]
        virtual = [band for band, value in zip(bands, kept_occupations) if value < 0.5]
        if virtual:
            virtual_template_orbitals[element] = {
                "bands_1based": virtual,
                "majority_occupations": kept_occupations.tolist(),
                "note": (
                    "empty free-atom orbitals used as extra reference functions; they enlarge "
                    "the IAO span, so this is an IAO+ basis and not the minimal-basis convention"
                ),
            }
        template_diag[element] = {**diag, "orbital_count": len(bands)}
        template_tests[element] = {
            "paw_identity": atomic_template_paw_identity_test(
                TEMPLATE_DIRS[element], raw, diag, load_count
            ) if with_template_tests else None,
            "real_space_gauge": gauge,
            "template_bands_1based": [bands[0], bands[-1]],
            "shell": shell_name,
            "majority_spin_occupations_of_kept_bands": kept_occupations.tolist(),
        }

    wav = Wavecar(calc / "WAVECAR")
    try:
        if int(wav.nspin) != 1:
            raise RuntimeError(f"only nspin=1 is handled, found {wav.nspin}")
        if len(k_weights) != wav.nk:
            raise RuntimeError(f"IBZKPT has {len(k_weights)} k points, WAVECAR has {wav.nk}")
        wavecar_kpoints = np.asarray([item[1] for item in wav.kinfo], dtype=np.float64)
        delta_k = (wavecar_kpoints - kvectors + 0.5) % 1.0 - 0.5
        if np.max(np.abs(delta_k)) > 1.0e-8:
            raise RuntimeError("IBZKPT and WAVECAR k-point coordinates/order disagree")
    except BaseException:
        wav.close()
        raise

    space_group_plan = None
    if time_reversal["ISYM"] == 1 and with_space_group_plan:
        incar_text = (calc / "INCAR").read_text(errors="replace")
        symprec_value = incar_value(incar_text, "SYMPREC")
        symprec = float(symprec_value) if symprec_value is not None else 1.0e-5
        if not np.isfinite(symprec) or symprec <= 0.0:
            wav.close()
            raise ValueError(f"SYMPREC must be finite and positive, got {symprec}")
        try:
            space_group_plan = prepare_space_group_expansion(
                atoms,
                grids,
                template_diag,
                atom_columns,
                kvectors,
                multiplicities,
                calc / "KPOINTS",
                symprec,
            )
        except BaseException:
            wav.close()
            raise
    return {
        "calc": calc, "shells": shells, "structure": structure, "atoms": atoms,
        "datasets": datasets, "elements": elements, "counts": counts, "n_oxygen": n_oxygen,
        "n_excluded": n_excluded, "fermi": fermi, "nelect": nelect, "k_weights": k_weights,
        "kvectors": kvectors, "wavecar_kvectors": wavecar_kpoints,
        "multiplicities": multiplicities,
        "time_reversal": time_reversal, "potcar_validation": potcar_validation,
        "labels": labels, "atom_columns": atom_columns, "width": width, "grids": grids,
        "template_diag": template_diag, "template_tests": template_tests,
        "virtual_template_orbitals": virtual_template_orbitals,
        "occupation_floor": occupation_floor, "skip_augmentation": skip_augmentation,
        "spectral_empty_bands": spectral_empty_bands, "basis_variant": basis_variant,
        "space_group_plan": space_group_plan,
        "wav": wav, "main_volume": abs(float(wav.vol)),
    }


def _process_k(context: dict, k_index: int) -> dict:
    """One k point. Identical code in the serial and the parallel path."""
    wav = context["wav"]
    structure, atoms, datasets = context["structure"], context["atoms"], context["datasets"]
    width, atom_columns = context["width"], context["atom_columns"]
    n_oxygen, n_excluded = context["n_oxygen"], context["n_excluded"]
    occupation_floor = context["occupation_floor"]
    skip_augmentation = context["skip_augmentation"]
    spectral_empty_bands = context["spectral_empty_bands"]
    k_weights, fermi = context["k_weights"], context["fermi"]

    block_started = time.time()
    energies = np.asarray(wav.kinfo[k_index][2], dtype=np.float64)
    occupations = np.asarray(wav.kinfo[k_index][3], dtype=np.float64)
    if (
        occupations.shape != energies.shape
        or not np.isfinite(occupations).all()
        or occupations.min() < -1.0e-8
        or occupations.max() > 1.0 + 1.0e-8
    ):
        raise RuntimeError(
            f"WAVECAR occupations at k={k_index + 1} must be finite in [0,1] "
            "before the explicit spin-degeneracy factor"
        )

    # deep O 2s manifold: exactly the lowest n_O bands, verified by the gap
    deep_gap = float(energies[n_oxygen] - energies[n_oxygen - 1]) if n_oxygen else None
    active = np.flatnonzero(occupations > occupation_floor)
    active = active[active >= n_excluded]
    if active.size == 0 or active[0] != n_excluded:
        raise RuntimeError(
            f"active window does not start at band {n_excluded + 1} for k={k_index + 1}"
        )
    bands = list(range(int(active[0]), int(active[-1]) + 1))
    if np.any(occupations[bands] <= occupation_floor):
        raise RuntimeError(f"active band window is not contiguous at k={k_index + 1}")

    gvec = wav.gvecs(k_index)
    kvector = np.asarray(wav.kinfo[k_index][1], dtype=np.float64)
    g_plus_k = gvec.astype(np.float64) + kvector[None, :]
    reference = build_reference(
        structure, g_plus_k, np.asarray(wav.B, dtype=np.float64),
        context["main_volume"], context["grids"], context["template_diag"], width,
    )
    matrices, gram_diag = build_paw_grams(
        wav, k_index, bands, reference, atoms, datasets, augment=not skip_augmentation
    )
    empty_bands: list[int] = []
    empty_reference_overlap = None
    if spectral_empty_bands and not skip_augmentation:
        stop_band = min(int(wav.nb), bands[-1] + 1 + spectral_empty_bands)
        empty_bands = list(range(bands[-1] + 1, stop_band))
        if empty_bands:
            empty_reference_overlap = empty_band_reference_overlap(
                wav, k_index, empty_bands, reference, atoms, datasets
            )
    del reference

    occupied_coordinates, reference_coordinates, occupied_lowdin, compact_diag = (
        compact_joint_coordinates(
            matrices["occupied_overlap"],
            matrices["cross_overlap"],
            matrices["reference_overlap"],
            RCOND,
        )
    )
    iaos, iao_diag = build_intrinsic_atomic_orbitals(
        reference_coordinates, occupied_coordinates, rcond=RCOND
    )
    factors = make_atomic_population_factors(occupied_coordinates, iaos, atom_columns)
    raw_factors = np.linalg.solve(occupied_lowdin, np.concatenate(factors, axis=1))

    # D_k = sum_n w_k f_n <IAO|psi_n><psi_n|IAO>;  factor 2 for spin degeneracy
    weight = 2.0 * k_weights[k_index] * occupations[bands]
    density = raw_factors.conj().T @ (weight[:, None] * raw_factors)

    # ---- empty bands, for the COOP-style spectrum only -------------
    # These never enter the density: their occupation is zero. They exist
    # so the spectrum can show whether an antibonding partner is genuinely
    # empty (pushed above E_F) rather than merely outside the window.
    empty_projection = None
    if empty_reference_overlap is not None:
        joint = np.concatenate((occupied_coordinates, reference_coordinates), axis=1)
        gram = np.real(np.einsum("ij,ij->i", joint, joint.conj()))
        width_o = occupied_coordinates.shape[1]

        # Validate the reconstruction on states whose answer is already
        # known: the Lowdin-occupied rows of the joint Gram are
        # [I, S_oo^-1/2 S_or], and feeding those back must return the
        # factors that make_atomic_population_factors built directly.
        normalized_cross = occupied_lowdin @ matrices["cross_overlap"]
        occupied_rows = np.concatenate(
            (np.eye(width_o, dtype=np.complex128), normalized_cross), axis=1
        )
        reference_projection_error = float(np.max(np.abs(
            project_onto_iao(occupied_rows, joint, gram, iaos)
            - np.concatenate(factors, axis=1)
        )))

        # An empty band is PAW-orthogonal to every occupied band, so its
        # joint overlap row is [0, S_er].
        empty_rows_overlap = np.concatenate(
            (np.zeros((empty_reference_overlap.shape[0], width_o), dtype=np.complex128),
             empty_reference_overlap), axis=1
        )
        empty_projection = project_onto_iao(empty_rows_overlap, joint, gram, iaos)
    else:
        reference_projection_error = None

    return {
        "k_index": k_index,
        "density": density,
        "coefficients": raw_factors,
        "empty_coefficients": empty_projection,
        "bands": bands,
        "empty_bands": empty_bands,
        "weight": weight,
        "occupations": occupations[bands],
        "empty_occupations": occupations[empty_bands] if empty_bands else np.empty(0),
        "energies": energies[bands] - fermi,
        "empty_energies": (energies[empty_bands] - fermi) if empty_bands else np.empty(0),
        "electrons": float(weight.sum()),
        "occupation_min": float(occupations.min()),
        "occupation_max": float(occupations.max()),
        "closure": iao_diag["occupied_projector_closure_max_abs_error"],
        "per_k": {
            "k_index_1based": k_index + 1,
            "k_weight": float(k_weights[k_index]),
            "active_band_range_1based": [bands[0] + 1, bands[-1] + 1],
            "active_band_count": len(bands),
            "deep_O2s_gap_eV": deep_gap,
            "PAW_gram": gram_diag,
            "joint_rank": compact_diag["joint_rank"],
            "iao_lowdin_rank": iao_diag["iao_lowdin"]["rank"],
            "occupied_projector_closure_max_abs_error": iao_diag[
                "occupied_projector_closure_max_abs_error"
            ],
            "occupied_span_frobenius_residual": iao_diag["occupied_span_frobenius_residual"],
            "atomic_factor_closure_max_abs_error": factor_closure_error(factors),
            "empty_band_count": len(empty_bands),
            "occupied_reprojection_max_abs_error": reference_projection_error,
            "wall_seconds": time.time() - block_started,
        },
    }


def assemble_output_k_blocks(context: dict, blocks: list[dict]) -> dict:
    """Return persisted k/state blocks in the convention appropriate to ISYM."""
    k_weights = context["k_weights"]
    isym = context["time_reversal"]["ISYM"]
    if isym == 0:
        density_matrices = np.stack([block["density"] for block in blocks])
        state_coefficients, state_rows = [], []
        empty_coefficients, empty_rows = [], []
        for block in blocks:
            k_index = block["k_index"]
            state_coefficients.append(block["coefficients"])
            for local, band in enumerate(block["bands"]):
                state_rows.append({
                    "state_index": len(state_rows),
                    "k_index": k_index + 1,
                    "band_index": band + 1,
                    "k_weight": float(k_weights[k_index]),
                    "occupation_f_0_to_2": float(2.0 * block["occupations"][local]),
                    "state_weight_W": float(block["weight"][local]),
                    "energy_relative_EF_eV": float(block["energies"][local]),
                })
            if block["empty_coefficients"] is not None:
                empty_coefficients.append(block["empty_coefficients"])
                for local, band in enumerate(block["empty_bands"]):
                    empty_rows.append({
                        "state_index": len(empty_rows),
                        "k_index": k_index + 1,
                        "band_index": band + 1,
                        "k_weight": float(k_weights[k_index]),
                        "occupation_f_0_to_2": float(2.0 * block["empty_occupations"][local]),
                        "energy_relative_EF_eV": float(block["empty_energies"][local]),
                    })
        return {
            "density_matrices_k": density_matrices,
            # Preserve the historical ISYM=0 bytes/gauge: the WAVECAR header and
            # IBZKPT text can differ by a few last-decimal roundoff units.
            "kpoints": context["wavecar_kvectors"].copy(),
            "state_coefficients": state_coefficients,
            "state_rows": state_rows,
            "empty_coefficients": empty_coefficients,
            "empty_rows": empty_rows,
            "expansion_rows": [],
            "checks": {
                "explicit_space_group_expansion": False,
                "expanded_state_density_max_abs_error": 0.0,
                "duplicate_symmetry_image_density_max_abs_error": 0.0,
                "expanded_k_weight_sum": float(k_weights.sum()),
            },
        }

    plan = context["space_group_plan"]
    if plan is None:
        raise RuntimeError("ISYM=1 parent context has no space-group expansion plan")
    density_matrices, output_kpoints = [], []
    state_coefficients, state_rows = [], []
    empty_coefficients, empty_rows = [], []
    expansion_rows = []
    density_closure = 0.0
    duplicate_covariance = 0.0
    output_k_index = 0

    for source_index, (block, star, multiplicity) in enumerate(
        zip(blocks, plan["stars"], context["multiplicities"])
    ):
        if block["k_index"] != source_index:
            raise RuntimeError("processed k blocks are not in source IBZ order")
        multiplicity = int(multiplicity)
        for image_in_star, image in enumerate(star, start=1):
            transform = iao_transform(
                plan, image["operation_index"], image["spatial_kpoint"]
            )
            transformed_density = transform_density(block["density"], transform)
            transformed_coefficients = transform_coefficients(block["coefficients"], transform)
            transformed_empty = (
                transform_coefficients(block["empty_coefficients"], transform)
                if block["empty_coefficients"] is not None else None
            )
            if image["time_reversed"]:
                transformed_density = transformed_density.conj()
                transformed_coefficients = transformed_coefficients.conj()
                if transformed_empty is not None:
                    transformed_empty = transformed_empty.conj()

            for alternative in image["alternatives"]:
                alternative_transform = iao_transform(
                    plan,
                    alternative["operation_index"],
                    alternative["spatial_kpoint"],
                )
                alternative_density = transform_density(block["density"], alternative_transform)
                if alternative["time_reversed"]:
                    alternative_density = alternative_density.conj()
                duplicate_covariance = max(
                    duplicate_covariance,
                    float(np.max(np.abs(alternative_density - transformed_density))),
                )

            image_density = transformed_density / multiplicity
            image_state_weight = block["weight"] / multiplicity
            density_from_states = transformed_coefficients.conj().T @ (
                image_state_weight[:, None] * transformed_coefficients
            )
            density_closure = max(
                density_closure,
                float(np.max(np.abs(density_from_states - image_density))),
            )
            density_matrices.append(image_density)
            output_kpoints.append(image["kpoint"])
            state_coefficients.append(transformed_coefficients)
            output_k_index += 1

            common = {
                "k_index": output_k_index,
                "source_k_index": source_index + 1,
                "symmetry_operation_index_1based": image["operation_index"] + 1,
                "time_reversed": int(image["time_reversed"]),
            }
            image_k_weight = float(k_weights[source_index] / multiplicity)
            for local, band in enumerate(block["bands"]):
                state_rows.append({
                    "state_index": len(state_rows),
                    **common,
                    "band_index": band + 1,
                    "k_weight": image_k_weight,
                    "occupation_f_0_to_2": float(2.0 * block["occupations"][local]),
                    "state_weight_W": float(image_state_weight[local]),
                    "energy_relative_EF_eV": float(block["energies"][local]),
                })
            if transformed_empty is not None:
                empty_coefficients.append(transformed_empty)
                for local, band in enumerate(block["empty_bands"]):
                    empty_rows.append({
                        "state_index": len(empty_rows),
                        **common,
                        "band_index": band + 1,
                        "k_weight": image_k_weight,
                        "occupation_f_0_to_2": float(2.0 * block["empty_occupations"][local]),
                        "energy_relative_EF_eV": float(block["empty_energies"][local]),
                    })
            expansion_rows.append({
                "output_k_index": output_k_index,
                "source_ibz_k_index": source_index + 1,
                "image_in_star": image_in_star,
                "star_multiplicity": multiplicity,
                "symmetry_operation_index_1based": image["operation_index"] + 1,
                "time_reversed": int(image["time_reversed"]),
                "k_x": float(image["kpoint"][0]),
                "k_y": float(image["kpoint"][1]),
                "k_z": float(image["kpoint"][2]),
                "source_ibz_weight": float(k_weights[source_index]),
                "expanded_k_weight": image_k_weight,
                "equivalent_transform_count": len(image["alternatives"]) + 1,
            })

    density_matrices_array = np.stack(density_matrices)
    scale = max(float(np.max(np.abs(density_matrices_array))), 1.0)
    if density_closure > 1.0e-10 * scale:
        raise RuntimeError(
            f"expanded state coefficients do not reproduce D(k): {density_closure:.3e}"
        )
    if duplicate_covariance > 1.0e-5 * scale:
        raise RuntimeError(
            "different symmetry operations that reach the same full k point disagree: "
            f"{duplicate_covariance:.3e}"
        )
    return {
        "density_matrices_k": density_matrices_array,
        "kpoints": np.asarray(output_kpoints, dtype=np.float64),
        "state_coefficients": state_coefficients,
        "state_rows": state_rows,
        "empty_coefficients": empty_coefficients,
        "empty_rows": empty_rows,
        "expansion_rows": expansion_rows,
        "checks": {
            "explicit_space_group_expansion": True,
            "expanded_state_density_max_abs_error": density_closure,
            "duplicate_symmetry_image_density_max_abs_error": duplicate_covariance,
            "expanded_k_weight_sum": float(
                sum(row["expanded_k_weight"] for row in expansion_rows)
            ),
        },
    }


_WORKER: dict = {}


def _worker_initialise(payload: dict) -> None:
    """Rebuild the k-independent context inside a worker process (spawn-safe)."""
    global _WORKER
    _WORKER = build_k_context(
        Path(payload["calc"]), payload["basis_variant"], payload["occupation_floor"],
        payload["skip_augmentation"], payload["spectral_empty_bands"],
        with_template_tests=False, with_space_group_plan=False,
    )


def _worker_process(k_index: int) -> dict:
    return _process_k(_WORKER, k_index)


def run(calc: Path, output: Path, occupation_floor: float, skip_augmentation: bool = False,
        spectral_empty_bands: int = 0, basis_variant: str = "o2s", workers: int = 1) -> dict:
    started_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    if output.exists():
        raise FileExistsError(f"immutable output already exists: {output}")
    if workers < 1:
        raise ValueError("workers must be >= 1")

    context = build_k_context(calc, basis_variant, occupation_floor, skip_augmentation,
                              spectral_empty_bands)
    try:
        wav = context["wav"]
        shells, width = context["shells"], context["width"]
        elements, counts = context["elements"], context["counts"]
        n_oxygen, n_excluded = context["n_oxygen"], context["n_excluded"]
        fermi, nelect = context["fermi"], context["nelect"]
        k_weights = context["k_weights"]
        labels = context["labels"]
        potcar_validation = context["potcar_validation"]
        time_reversal = context["time_reversal"]
        template_tests = context["template_tests"]
        virtual_template_orbitals = context["virtual_template_orbitals"]
        wav_meta = {
            "nspin": int(wav.nspin), "nk": int(wav.nk), "nbands": int(wav.nb),
            "encut_eV": float(wav.encut), "FFT_grid": [int(v) for v in wav.ng],
        }
        workers = min(workers, int(wav.nk))

        if workers == 1:
            blocks = []
            for k_index in range(wav.nk):
                block = _process_k(context, k_index)
                blocks.append(block)
                print(
                    f"  k {k_index + 1:2d}/{wav.nk}: bands {block['bands'][0]+1}-"
                    f"{block['bands'][-1]+1}, closure={block['closure']:.2e}, "
                    f"{block['per_k']['wall_seconds']:.1f} s",
                    flush=True,
                )
        else:
            # k points are independent; each worker rebuilds the same context and
            # opens its own WAVECAR handle. Results are re-sorted by k before the
            # sum, so the accumulation order is the same as the serial path; the
            # remaining difference (~2e-15 measured) is the BLAS reduction order
            # at a different thread count, not the algorithm.
            #
            # The thread cap is not optional. The per-k work is one long chain of
            # large GEMMs that already saturates every core, so unrestricted
            # workers just fight each other: measured on 12 logical CPUs,
            # 12 k points, clean RuO2(100) --
            #   serial                       79.2 s   (bit-identical to the archive)
            #   4 workers, threads uncapped  90.1 s   (slower than serial)
            #   6 workers x 2 threads        43.2 s   (1.8x, agrees to 2e-15)
            payload = {
                "calc": str(calc), "basis_variant": basis_variant,
                "occupation_floor": occupation_floor,
                "skip_augmentation": skip_augmentation,
                "spectral_empty_bands": spectral_empty_bands,
            }
            threads = max(1, (os.cpu_count() or workers) // workers)
            print(f"  running {wav.nk} k points on {workers} worker processes "
                  f"x {threads} BLAS threads", flush=True)
            # spawned children inherit the environment at import time, which is
            # the only moment the BLAS thread count can still be set
            saved = {name: os.environ.get(name) for name in _THREAD_VARIABLES}
            os.environ.update({name: str(threads) for name in _THREAD_VARIABLES})
            try:
                with multiprocessing.get_context("spawn").Pool(
                    processes=workers, initializer=_worker_initialise, initargs=(payload,)
                ) as pool:
                    blocks = []
                    for block in pool.imap_unordered(_worker_process, range(wav.nk)):
                        blocks.append(block)
                        print(
                            f"  k {block['k_index'] + 1:2d}/{wav.nk}: bands "
                            f"{block['bands'][0]+1}-{block['bands'][-1]+1}, "
                            f"closure={block['closure']:.2e}, "
                            f"{block['per_k']['wall_seconds']:.1f} s",
                            flush=True,
                        )
            finally:
                for name, value in saved.items():
                    if value is None:
                        os.environ.pop(name, None)
                    else:
                        os.environ[name] = value
            blocks.sort(key=lambda item: item["k_index"])

        assembled = assemble_output_k_blocks(context, blocks)
        density_matrices_k = assembled["density_matrices_k"]
        kpoint_fractional = assembled["kpoints"]
        state_coefficients = assembled["state_coefficients"]
        state_rows = assembled["state_rows"]
        empty_coefficients = assembled["empty_coefficients"]
        empty_rows = assembled["empty_rows"]
        expansion_rows = assembled["expansion_rows"]
        expansion_checks = assembled["checks"]
        density = density_matrices_k.sum(axis=0)
        per_k, electrons = [], 0.0
        occupation_min, occupation_max = float("inf"), float("-inf")
        for block in blocks:
            electrons += block["electrons"]
            occupation_min = min(occupation_min, block["occupation_min"])
            occupation_max = max(occupation_max, block["occupation_max"])
            per_k.append(block["per_k"])
    finally:
        context["wav"].close()

    # ISYM=0 retains the compact time-reversal-folded convention, where taking
    # Re[D] performs the explicit k/-k sum.  ISYM=1 has already been expanded to
    # the complete spatial + time-reversal mesh, so its residual imaginary part
    # is an independent cancellation diagnostic.
    imaginary = float(np.max(np.abs(density.imag)))
    hermiticity = float(np.max(np.abs(density - density.conj().T)))
    if hermiticity > 1.0e-9 * max(float(np.max(np.abs(density))), 1.0):
        raise RuntimeError(f"accumulated IAO density is not Hermitian: {hermiticity:.3e}")
    density = np.ascontiguousarray(density.real)
    density = 0.5 * (density + density.T)

    values, vectors = np.linalg.eigh(density)
    order = np.argsort(values)[::-1]
    values, vectors = values[order], vectors[:, order]
    negative = float(min(values.min(), 0.0))
    if negative < -1.0e-8 * max(values.max(), 1.0):
        raise RuntimeError(f"IAO density is not positive semi-definite (min eigenvalue {negative:.3e})")
    values = np.clip(values, 0.0, None)
    basis = vectors.T  # column mu holds the coordinates of IAO_mu

    reconstruction = float(np.max(np.abs((basis.T * values) @ basis - density)))
    orthonormality = float(np.max(np.abs(basis.T @ basis - np.eye(width))))
    trace = float(values.sum())
    expected_active_electrons = nelect - 2.0 * n_excluded
    electron_count_error = abs(electrons - expected_active_electrons)
    neutral_valence_electrons = sum(
        counts[record["element"]] * record["zval"]
        for record in potcar_validation["main"]
    )
    isym = time_reversal["ISYM"]
    density_scale = max(float(np.max(np.abs(density_matrices_k))), 1.0)
    expected_output_k_count = (
        int(np.sum(context["multiplicities"])) if isym == 1 else len(k_weights)
    )

    checks = {
        "supported_ISYM_0_or_1": isym in (0, 1),
        "ISYM1_space_group_expansion_completed": (
            isym == 0 or expansion_checks["explicit_space_group_expansion"]
        ),
        "output_k_block_count_matches_folding": len(density_matrices_k) == expected_output_k_count,
        "output_k_weights_sum_one": (
            abs(expansion_checks["expanded_k_weight_sum"] - 1.0) <= 1.0e-12
        ),
        "expanded_state_density_closure": (
            expansion_checks["expanded_state_density_max_abs_error"]
            <= 1.0e-10 * density_scale
        ),
        "equivalent_symmetry_operations_are_covariant": (
            expansion_checks["duplicate_symmetry_image_density_max_abs_error"]
            <= 1.0e-5 * density_scale
        ),
        "ISYM1_explicit_time_reversal_imaginary_cancellation": (
            isym == 0 or imaginary <= 1.0e-10 * max(trace, 1.0)
        ),
        "main_template_POTCAR_dataset_identity": potcar_validation["all_datasets_match"],
        "standard_Ru_valence": potcar_validation["standard_ru_ok"],
        "k_weight_sum_one": abs(float(k_weights.sum()) - 1.0) <= 1.0e-12,
        "occupation_parser_range_0_to_1": occupation_min >= -1.0e-8 and occupation_max <= 1.0 + 1.0e-8,
        "active_electron_count_closure": electron_count_error <= max(1.0e-6, 1.0e-8 * nelect),
        "all_k_PAW_orthonormal": skip_augmentation or all(
            item["PAW_gram"]["occupied_PAW_orthonormality_max_abs_error"] <= 5.0e-5 for item in per_k
        ),
        "all_k_finite": all(item["PAW_gram"]["finite"] for item in per_k),
        "all_k_iao_rank_full": all(item["iao_lowdin_rank"] == width for item in per_k),
        "all_k_occupied_projector_closure": all(
            item["occupied_projector_closure_max_abs_error"] <= 1.0e-8 for item in per_k
        ),
        "all_k_occupied_span_residual": all(
            item["occupied_span_frobenius_residual"]
            <= 1.0e-8 * np.sqrt(item["active_band_count"])
            for item in per_k
        ),
        "all_k_atomic_factor_closure": all(
            item["atomic_factor_closure_max_abs_error"] <= 1.0e-8 for item in per_k
        ),
        "empty_band_projection_reproduces_occupied": all(
            item["occupied_reprojection_max_abs_error"] is None
            or item["occupied_reprojection_max_abs_error"] <= 1.0e-8
            for item in per_k
        ),
        # only load-bearing when the manifold is being cut away; with O 2s inside
        # the template the window starts at band 1 and there is nothing to separate
        "deep_O2s_gap_above_5eV": n_excluded == 0 or all(
            item["deep_O2s_gap_eV"] is None or item["deep_O2s_gap_eV"] > 5.0 for item in per_k
        ),
        "density_hermitian": hermiticity <= 1.0e-9 * max(trace, 1.0),
        "density_positive_semidefinite": negative >= -1.0e-8 * max(values.max(), 1.0),
        "density_trace_not_above_electron_count": (
            trace <= electrons + max(1.0e-6, 1.0e-6 * electrons)
        ),
        "eigen_reconstruction": reconstruction <= 1.0e-10,
        "basis_orthonormal": orthonormality <= 1.0e-10,
    }
    report = {
        "status": "pass" if all(checks.values()) else "fail",
        "method": "direct full-cell Lowdin IAO density matrix (PAW-IAO-PDC v2 upstream)",
        "periodic_density_convention": (
            "iao_density_matrices_k.npy stores weighted D(k); "
            "D[mu(0),nu(R)] = sum_k exp(-2*pi*i*k.R) D_k[mu,nu]"
        ),
        "calculation": str(calc),
        "started_at": started_at,
        "completed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "composition": counts,
        "fermi_eV": fermi,
        "WAVECAR": wav_meta,
        "stored_irreducible_k_point_count": int(wav_meta["nk"]),
        "persisted_k_block_count": len(density_matrices_k),
        "iao_columns": width,
        "state_count": len(state_rows),
        "empty_state_count": len(empty_rows),
        "spectral_empty_bands_requested": spectral_empty_bands,
        "empty_band_note": (
            "Unoccupied projections <psi|IAO> are stored for the COOP-style spectrum only. "
            "They carry zero occupation and never enter the density matrix, its trace, or any "
            "channel strength."
        ),
        "basis_variant": basis_variant,
        "worker_processes": workers,
        "basis_variant_bands_1based": {
            element: [shells[element][0][0], shells[element][0][-1]] for element in elements
        },
        "virtual_template_orbitals": virtual_template_orbitals or None,
        "deep_O2s_bands_excluded_1based": [1, n_excluded] if n_excluded else None,
        "occupation_floor": occupation_floor,
        "raw_occupation_range_0_to_1": [occupation_min, occupation_max],
        "NELECT": nelect,
        "neutral_valence_electrons_from_POTCAR": neutral_valence_electrons,
        "cell_charge_relative_to_neutral_e": neutral_valence_electrons - nelect,
        "expected_active_electrons_after_O2s_exclusion": expected_active_electrons,
        "active_electrons_in_window": electrons,
        "active_electron_count_abs_error": electron_count_error,
        "iao_density_trace": trace,
        "template_spilling_electrons": electrons - trace,
        "template_spilling_fraction": (electrons - trace) / electrons if electrons else 0.0,
        "eigenvalue_max": float(values.max()),
        "eigenvalue_min": float(values.min()),
        "time_reversal": time_reversal,
        "space_group_expansion": (
            {
                **context["space_group_plan"]["report"],
                **expansion_checks,
                "output_convention": (
                    "explicit full automatic k mesh; every D(k) and state row carries its "
                    "individual full-mesh weight"
                ),
                "mapping_file": "kpoint_expansion.csv",
            }
            if isym == 1 else None
        ),
        "POTCAR": potcar_validation,
        "density_hermiticity_max_abs_error": hermiticity,
        "time_reversal_paired_imaginary_part_max_abs": imaginary,
        "eigen_reconstruction_max_abs_error": reconstruction,
        "basis_orthonormality_max_abs_error": orthonormality,
        "shells": {element: shells[element][1] for element in elements},
        "templates": template_tests,
        "per_k": per_k,
        "checks": checks,
        "limitations": [
            "No active-space truncation: all occupied states in the declared template-consistent "
            "band window are kept; density eigenvalues are not truncated.",
            "Template spilling is the only incompleteness; it is reported per structure and must be "
            "compared before any cross-structure claim.",
            (
                "O 2s is included in both the band window and the template, consistently."
                if n_excluded == 0 else
                "O 2s is excluded from both the band window and the template, consistently."
            ),
            "Validated scope: standard Ru POTCAR, o2s or legacy valence IAO basis, ISYM=0 or "
            "ISYM=1 on an automatic Gamma/Monkhorst-Pack mesh, ISPIN=1, no SOC/noncollinear "
            "mode, and WAVECAR occupations encoded on [0,1].",
            "For ISYM=1, density/PDC, IAO-space energy analyses and real-space channel-field "
            "reconstruction are supported. The field builders regenerate each missing scalar "
            "plane-wave star image from the reported fractional rotation/translation, with "
            "strict G-vector, k-point, norm and BvK phase checks.",
            "No bond order, bond energy, bond strength or rupture claim is produced here.",
        ],
    }
    if report["status"] != "pass":
        raise RuntimeError(f"IAO density validation failed: {checks}")

    output.parent.mkdir(parents=True, exist_ok=True)
    staged = Path(tempfile.mkdtemp(prefix=".iao_density.", dir=output.parent))
    np.save(staged / "density_eigenvalues.npy", values, allow_pickle=False)
    np.save(staged / "iao_basis.npy", basis, allow_pickle=False)
    np.save(staged / "iao_density_matrix.npy", density, allow_pickle=False)
    # Keep the weighted complex D(k) blocks: lattice-image bonds require their
    # Fourier phases and cannot be recovered from the R=0 sum above.
    np.save(staged / "iao_density_matrices_k.npy", density_matrices_k, allow_pickle=False)
    np.save(staged / "kpoint_fractional_coordinates.npy", kpoint_fractional, allow_pickle=False)
    np.save(
        staged / "iao_state_coefficients.npy",
        np.concatenate(state_coefficients, axis=0).astype(np.complex128),
        allow_pickle=False,
    )
    if empty_rows:
        np.save(
            staged / "iao_state_coefficients_empty.npy",
            np.concatenate(empty_coefficients, axis=0).astype(np.complex128),
            allow_pickle=False,
        )
        with (staged / "state_map_empty.csv").open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(empty_rows[0]))
            writer.writeheader()
            writer.writerows(empty_rows)
    if expansion_rows:
        with (staged / "kpoint_expansion.csv").open(
            "w", newline="", encoding="utf-8"
        ) as handle:
            writer = csv.DictWriter(handle, fieldnames=list(expansion_rows[0]))
            writer.writeheader()
            writer.writerows(expansion_rows)
    with (staged / "state_map.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(state_rows[0]))
        writer.writeheader()
        writer.writerows(state_rows)
    with (staged / "iao_labels.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(labels[0]))
        writer.writeheader()
        writer.writerows(labels)
    (staged / "iao-density-validation.json").write_text(json_text(report), encoding="utf-8")
    os.replace(staged, output)
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--calc", type=Path, required=True)
    parser.add_argument("--templates", type=Path, required=True, help="directory containing Ru/, O/, H/ atomic calculations")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--occupation-floor", type=float, default=1.0e-6)
    parser.add_argument("--spectral-empty-bands", type=int, default=0,
                        help="also project this many unoccupied bands per k onto the IAOs, "
                             "for the COOP-style spectrum; they never enter the density")
    parser.add_argument("--skip-paw-augmentation", action="store_true",
                        help="DIAGNOSTIC ONLY: drop Q_ij from every overlap")
    parser.add_argument("--basis-variant", choices=sorted(BASIS_VARIANTS), default="o2s",
                        help="default o2s: O 2s+2p, Ru 5s+4d, H 1s; valence retains "
                             "the legacy O-2p-only definition")
    parser.add_argument("--workers", type=int, default=1,
                        help="k points are independent; run this many worker processes, each "
                             "capped to cpu_count/workers BLAS threads (uncapped workers are "
                             "SLOWER than serial). Budget ~1 GB per worker. --workers 1 "
                             "reproduces the archived runs bit for bit; more workers agree to "
                             "~2e-15, the BLAS reduction order")
    args = parser.parse_args()
    TEMPLATE_DIRS.update({element: args.templates.resolve() / element for element in ("Ru", "O", "H")})
    report = run(args.calc.resolve(), args.output.resolve(), args.occupation_floor,
                 args.skip_paw_augmentation, args.spectral_empty_bands, args.basis_variant,
                 args.workers)
    print(
        json.dumps(
            {
                "status": report["status"],
                "basis_variant": report["basis_variant"],
                "shells": report["shells"],
                "iao_columns": report["iao_columns"],
                "active_electrons_in_window": report["active_electrons_in_window"],
                "iao_density_trace": report["iao_density_trace"],
                "template_spilling_fraction": report["template_spilling_fraction"],
            },
            indent=2,
            allow_nan=False,
        )
    )


if __name__ == "__main__":
    main()
